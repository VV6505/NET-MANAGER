package com.netgamer.qlquannet.model;

public class Game {
    private String maGame;
    private String tenGame;
    private double giaGame;
    private String theLoai;
    private String moTa;
    private String hinhAnh;

    public String getMaGame() {
        return maGame;
    }

    public void setMaGame(String maGame) {
        this.maGame = maGame;
    }

    public String getTenGame() {
        return tenGame;
    }

    public void setTenGame(String tenGame) {
        this.tenGame = tenGame;
    }

    public double getGiaGame() {
        return giaGame;
    }

    public void setGiaGame(double giaGame) {
        this.giaGame = giaGame;
    }

    public String getTheLoai() {
        return theLoai;
    }

    public void setTheLoai(String theLoai) {
        this.theLoai = theLoai;
    }

    public String getMoTa() {
        return moTa;
    }

    public void setMoTa(String moTa) {
        this.moTa = moTa;
    }

    public String getHinhAnh() {
        return hinhAnh;
    }

    public void setHinhAnh(String hinhAnh) {
        this.hinhAnh = hinhAnh;
    }
}

